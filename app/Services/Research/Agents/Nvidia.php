<?php

namespace App\Services\Research\Agents;

use App\Models\Research\Document;
use App\Models\Research\Source;
use App\Services\Research\Blueprint;
use App\Services\Research\Context;
use League\CommonMark\Environment\Environment;
use League\CommonMark\Extension\CommonMark\CommonMarkCoreExtension;
use League\CommonMark\Extension\CommonMark\Node\Block\Heading;
use League\CommonMark\Parser\MarkdownParser;

class Nvidia extends BaseAgent
{
    protected array $inputs = ['web_search' => 'sometimes|boolean'];

    protected array $tools = ['nvidia.deep_researcher.2_2', 'scoped_search', 'verified_gateway', 'manuscript.proposal'];

    protected array $rules = ['report' => 'required|string', 'upstream_commit' => 'required|string', 'engine' => 'required|string', 'sections' => 'required|array|min:1', 'base_version' => 'required|integer', 'source_ids' => 'present|array', 'disclosure' => 'required|string'];

    public function execute(Context $ctx): array
    {
        $checkpoint = $ctx->task->checkpoint ?? [];
        if (isset($checkpoint['completed_report'])) {
            return $checkpoint['completed_report'];
        }
        $base = (int) ($checkpoint['base_version'] ?? Document::where('project_id', $ctx->task->project_id)->value('version'));
        $ctx->checkpoint(['base_version' => $base]);
        $out = app(Blueprint::class)->research($ctx);
        $sources = Source::where('project_id', $ctx->task->project_id)->get()->keyBy('url');
        $labels = [];
        foreach (explode("\n", $out['report']) as $line) {
            if (preg_match('/^\s*\[?(\d+)\]?[.\s:].*(https?:\/\/[^\s)<>]+)/u', $line, $m) && isset($sources[rtrim($m[2], '.')])) {
                $labels[$m[1]] = $sources[rtrim($m[2], '.')]->id;
            }
        }
        $env = new Environment([]);
        $env->addExtension(new CommonMarkCoreExtension);
        $root = (new MarkdownParser($env))->parse($out['report']);
        $sections = [['heading' => 'Research report', 'paragraphs' => []]];
        foreach ($root->children() as $node) {
            $text = '';
            $ids = [];
            $walk = $node->walker();
            while ($event = $walk->next()) {
                if (! $event->isEntering()) {
                    continue;
                }$n = $event->getNode();
                if (method_exists($n, 'getLiteral')) {
                    $text .= $n->getLiteral();
                }if (method_exists($n, 'getUrl')) {
                    $url = rtrim($n->getUrl(), '.');
                    if (isset($sources[$url])) {
                        $ids[] = $sources[$url]->id;
                    }
                }
            }
            foreach ($labels as $label => $id) {
                if (str_contains($text, '['.$label.']')) {
                    $ids[] = $id;
                }
            }
            $text = trim($text);
            if ($text === '') {
                continue;
            }
            if ($node instanceof Heading) {
                if (! $sections[array_key_last($sections)]['paragraphs']) {
                    $sections[array_key_last($sections)]['heading'] = mb_substr($text, 0, 300);
                } else {
                    $sections[] = ['heading' => mb_substr($text, 0, 300), 'paragraphs' => []];
                }
            } else {
                foreach (mb_str_split($text, 5000) as $part) {
                    $sections[array_key_last($sections)]['paragraphs'][] = ['text' => $part, 'source_ids' => array_values(array_unique($ids))];
                }
            }
        }
        $sections = array_values(array_filter($sections, fn ($s) => count($s['paragraphs'])));
        abort_unless(count($sections), 502, 'NVIDIA returned an empty report.');
        $ids = Source::where('project_id', $ctx->task->project_id)->pluck('id')->all();
        $result = $out + ['sections' => $sections, 'source_ids' => $ids, 'base_version' => $base, 'disclosure' => 'Generated by NVIDIA Deep Researcher release/2.2. Review retrieved sources and approve the manuscript before treating it as final. No experiments were executed.'];
        $ctx->checkpoint(['base_version' => $base, 'completed_report' => $result]);

        return $result;
    }
}
